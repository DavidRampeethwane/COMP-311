public class Question3 {
    public static void main(String[] args) {
        int num = 2;                // initialize the variable num to 2, which is the first even number

        while (num <= 50) {         // while loop that continues as long as num is less than or equal to 50
            System.out.println(num);// print the current even number
            num += 2;               // increment num by 2 to get the next even number
        }
    }
}
